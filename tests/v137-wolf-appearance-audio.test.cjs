assert.match(html,/function ns137PlayRealWolfHowl\(\)/);
assert.match(html,/name==='wolfHowl'&&ns137PlayRealWolfHowl\(\)/);
assert.match(html,/wolfHowl:3400/,'howl cooldown must avoid many overlapping clips');
assert.match(html,/id='ns137SoundEnable'/,'automatic preview must allow touch to unlock audio');
assert.match(licenses,/public domain/);
assert.match(html,/Wolf_howls\.ogg/);
const scripts=[...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)].filter(m=>!/\bsrc=/.test(m[1]));
assert.equal(scripts.length,4);
for(const m of scripts)new vm.Script(m[2]);
