'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('public/index.html','utf8'),code=fs.readFileSync('addons/ns95-progress.inline.js','utf8');
let n=0;function eq(a,b,k){assert.equal(a,b,k);n++}function ok(a,k){assert.ok(a,k);n++}
new vm.Script(code);n++;
const context={NET:{role:''},mpProgress:{ranks:{mana:12,arcana:10}},meta:{ranks:{mana:3,arcana:3}},window:{}};
vm.runInNewContext(code,context);
const api=context.window.__NS95_PROGRESS;
const solo={ns93MaxMana:64,ns93Mana:64,ns93ManaRegen:2.5};
api.apply(solo);
eq(solo.ns93MaxMana,88,'solo 3 ranks add +24 MP');
eq(solo.ns93ManaRegen,2.86,'solo regen scales modestly');
ok(solo.ns95SpellMult<1.05,'solo +magic damage capped');
const coop={ns93MaxMana:102,ns93Mana:102,ns93ManaRegen:4.3,ns95ProfileRanks:{mana:12,arcana:10}};
context.NET.role='host';api.apply(coop);
eq(coop.ns93MaxMana,150,'coop mage ranks add +48 MP');
ok(coop.ns93ManaRegen<5.2,'regen remains bounded');
ok(coop.ns95SpellMult<1.09,'arcana bonus below 9%');
for(let i=0;i<4;i++)ok(api.boost(coop),'in-run mana choice '+i+' accepted');
eq(coop.ns93MaxMana,182,'four in-run picks yield +32 MP');
ok(!api.boost(coop),'fifth in-run mana boost rejected');
eq(coop.ns95RunManaRanks,4,'max 4 battle picks');
const noMana={ns93MaxMana:64,ns93Mana:64,ns93ManaRegen:2.5,ns95ProfileRanks:{}};
api.apply(noMana);
eq(noMana.ns93MaxMana,64,'existing players without progress unchanged');
ok(html.includes("mana:{icon:'✧',name:'REZERVA MANE'"),'mana in original multiplayer skill grid');
ok(html.includes("arcana:{icon:'☄',name:'VEŠTINA MAGIJE'"),'arcana in original multiplayer grid');
ok(html.includes("mana:{name:'REZERVA MANE'"),'mana in original solo base');
ok(html.includes("arcana:{name:'IZUČAVANJE MAGIJE'"),'arcana in original solo base');
ok(html.includes("NS95_PROGRESS.boost(p)"),'mana choice uses the shared capped function');
ok(html.includes("const spikes=NS94_FX.spikes")||html.includes("NS94_FX.spikes"),'previous low-FPS magic optimization retained');
ok(html.includes("const NS92_CHALLENGES="),'prior daily and weekly achievements preserved');
console.log('PASS '+n+' v95 progression checks: old upgrades preserved, solo+co-op mana, small damage and regen, four picks only.');
